const FALLBACK_LANGS = ['sw', 'ln', 'kg', 'tl']

FALLBACK_LANGS.forEach(code => {
  translations[code] = translations.fr
})

export function useTranslation() {
  const ctx = useContext(LangContext)
  if (ctx) return ctx

  const [lang, setLangState] = useState(() => localStorage.getItem(LANG_KEY) || 'fr')

  useEffect(() => {
    localStorage.setItem(LANG_KEY, lang)
  }, [lang])

  const setLang = useCallback((code) => {
    setLangState(code)
    localStorage.setItem(LANG_KEY, code)
  }, [])

  const t = useCallback((key, params) => {
    const dict = translations[lang] || translations.fr
    let str = dict[key]
    if (str === undefined) {
      str = translations.fr[key]
    }
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v)
      })
    }
    return str
  }, [lang])

  return { t, lang, setLang }
}

export { LangContext }
export default translations

export function LangProvider({ children }) {
  const value = useTranslation()
  return createElement(LangContext.Provider, { value }, children)
}
